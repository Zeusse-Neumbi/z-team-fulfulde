import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { loadAll, releaseErrors } from "./loader";

const root = fileURLToPath(new URL("../", import.meta.url));
const release = process.argv.includes("--release");
const fixture = process.argv.includes("--fixture");
const data = loadAll();

if (data.warnings.length) {
  console.warn(`[phrasebank] ${data.warnings.length} warning(s) in development data:`);
  for (const warning of data.warnings.slice(0, 20)) console.warn(`  - ${warning}`);
  if (data.warnings.length > 20) console.warn(`  ... and ${data.warnings.length - 20} more`);
}

if (release) {
  const errors = releaseErrors(data);
  if (errors.length) {
    console.error(`[phrasebank] release build failed with ${errors.length} error(s):`);
    for (const error of errors) console.error(`  - ${error}`);
    process.exit(1);
  }
}

function fixtureTarget(id: string, sources: string[]): string {
  // Test-only: keep the original strings after the marker so every protected
  // value is still byte-identical. This is never shipped.
  return `⟦FF:${id}⟧ ${sources.join(" ")}`;
}

const units = fixture
  ? data.translationUnits.map((unit) => ({
      ...unit,
      target: {
        ff: fixtureTarget(unit.id, [unit.source.fr, unit.source.en]),
      },
    }))
  : data.translationUnits;

const phrases = fixture
  ? data.phrases.map((phrase) => ({ ...phrase, ff: `⟦FF:${phrase.id}⟧` }))
  : data.phrases;

const output = `// Generated by src/build.ts — do not edit by hand.
import type { PhraseEntry, TranslationUnit } from "@zteam/shared";

export const tmVersion = ${JSON.stringify(data.tmVersion)};
export const phrasebankVersion = ${JSON.stringify(data.phrasebankVersion)};

export const translationUnits: TranslationUnit[] = ${JSON.stringify(units, null, 2)};

export const phrases: PhraseEntry[] = ${JSON.stringify(phrases, null, 2)};

export const numbers = ${JSON.stringify(data.numbers, null, 2)} as const;
`;

const target = fixture ? "src/generated.fixture.ts" : "src/generated.ts";
writeFileSync(`${root}${target}`, output, "utf8");
if (fixture) {
  writeFileSync(
    `${root}src/fixture.ts`,
    'export { phrasebankVersion, phrases, numbers, tmVersion, translationUnits } from "./generated.fixture";\n',
    "utf8",
  );
}
console.log(
  `[phrasebank] generated ${units.length} TM units and ${phrases.length} phrases${
    fixture ? " (fixture)" : release ? " (release)" : ""
  }`,
);
