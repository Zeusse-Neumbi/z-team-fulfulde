import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import type { LanguageTarget } from "@zteam/shared";
import { type PackSource, loadAll, loadRegistry, releaseErrors, releaseGate } from "./loader";

const root = fileURLToPath(new URL("../", import.meta.url));
const release = process.argv.includes("--release");
const fixture = process.argv.includes("--fixture");
const packs = loadAll();
const registry = new Map(loadRegistry().map((entry) => [entry.code, entry]));
const codes = Object.keys(packs).sort();

const warnings = codes.flatMap((code) => {
  const pack = packs[code];
  return pack ? pack.warnings.map((warning) => `${code}: ${warning}`) : [];
});

if (warnings.length) {
  console.warn(`[phrasebank] ${warnings.length} warning(s) in development data:`);
  for (const warning of warnings.slice(0, 20)) console.warn(`  - ${warning}`);
  if (warnings.length > 20) console.warn(`  ... and ${warnings.length - 20} more`);
}

if (release) {
  // A draft or text-only language is allowed; a validated one must pass. The
  // panel still shows every draft as `packValidated: false`.
  const errors = releaseGate(packs);
  if (errors.length) {
    console.error(`[phrasebank] release build failed with ${errors.length} error(s):`);
    for (const error of errors) console.error(`  - ${error}`);
    process.exit(1);
  }
}

function marker(id: string, lang: string): string {
  return `⟦${lang.toUpperCase()}:${id}⟧`;
}

function fixtureTargets(
  target: Record<string, LanguageTarget>,
  id: string,
  suffix = "",
): Record<string, LanguageTarget> {
  // Test-only: keep the original strings after the marker so every protected
  // value is still byte-identical. The marker names the target language so a
  // fub fixture and a ybb fixture stay distinguishable.
  return Object.fromEntries(
    Object.entries(target).map(([lang, value]) => [
      lang,
      { ...value, text: `${marker(id, lang)}${suffix}` },
    ]),
  );
}

function packSourceOf(code: string): PackSource | "fixture" {
  if (fixture) return "fixture";
  return packs[code]?.packSource ?? "validated";
}

function packValidatedOf(code: string): boolean {
  const pack = packs[code];
  if (fixture || !pack) return false;
  return pack.status === "validated" && releaseErrors(pack).length === 0;
}

const generated = Object.fromEntries(
  codes.map((code) => {
    const pack = packs[code];
    if (!pack) throw new Error(`Missing language pack: ${code}`);
    const entry = registry.get(code);
    return [
      code,
      {
        code,
        endonym: entry?.endonym ?? code,
        names: entry?.names ?? {},
        status: pack.status,
        packSource: packSourceOf(code),
        packValidated: packValidatedOf(code),
        speech: {
          provider: entry?.speech.provider ?? "none",
          model: entry?.speech.model ?? "",
          tone: entry?.speech.tone ?? "none",
          voice: entry?.speech.voice ?? "none",
        },
        tmVersion: pack.tmVersion,
        phrasebankVersion: pack.phrasebankVersion,
        translationUnits: fixture
          ? pack.translationUnits.map((unit) => ({
              ...unit,
              target: fixtureTargets(
                unit.target,
                unit.id,
                ` ${unit.source.fr} ${unit.source.en}`,
              ),
            }))
          : pack.translationUnits,
        phrases: fixture
          ? pack.phrases.map((phrase) => ({
              ...phrase,
              target: fixtureTargets(phrase.target, phrase.id),
            }))
          : pack.phrases,
        numbers: pack.numbers,
      },
    ];
  }),
);

const output = `// Generated by src/build.ts — do not edit by hand.
import type { NumbersLexicon, PhraseEntry, TranslationUnit } from "@zteam/shared";

export interface Pack {
  code: string;
  endonym: string;
  names: Record<string, string>;
  status: "validated" | "draft" | "text-only";
  packSource: "validated" | "mt" | "fixture";
  /** True only when the language is validated and the release gate agrees. */
  packValidated: boolean;
  speech: {
    provider: string;
    model: string;
    tone: "none" | "partial" | "full";
    voice: "bundled" | "api" | "none";
  };
  tmVersion: string;
  phrasebankVersion: string;
  translationUnits: TranslationUnit[];
  phrases: PhraseEntry[];
  numbers: NumbersLexicon;
}

export const languageCodes: string[] = ${JSON.stringify(codes, null, 2)};

export const languages: Record<string, Pack> = ${JSON.stringify(generated, null, 2)};
`;

const provenance = `// Generated by src/build.ts — do not edit by hand.
export type PackSource = "validated" | "mt" | "fixture";

/**
 * Where each bundled language's targets came from. The panel reads this to
 * label a draft pack: a machine-translated pack must never look validated.
 * "packValidated" is true only for a validated language that passes the gate.
 */
export const packSource: Record<string, PackSource> = ${JSON.stringify(
  Object.fromEntries(codes.map((code) => [code, packSourceOf(code)])),
  null,
  2,
)};

export const packValidated: Record<string, boolean> = ${JSON.stringify(
  Object.fromEntries(codes.map((code) => [code, packValidatedOf(code)])),
  null,
  2,
)};
`;

const target = fixture ? "src/generated.fixture.ts" : "src/generated.ts";
writeFileSync(`${root}${target}`, output, "utf8");
writeFileSync(
  `${root}${fixture ? "src/generated.provenance.fixture.ts" : "src/generated.provenance.ts"}`,
  provenance,
  "utf8",
);
if (fixture) {
  writeFileSync(
    `${root}src/fixture.ts`,
    'export { languageCodes, languages } from "./generated.fixture";\nexport { packSource, packValidated } from "./generated.provenance.fixture";\n',
    "utf8",
  );
}
const summary = codes
  .map((code) => {
    const pack = packs[code];
    return `${code} (${pack?.translationUnits.length ?? 0} units, ${
      pack?.phrases.length ?? 0
    } phrases, ${pack?.status ?? "?"})`;
  })
  .join(", ");
console.log(
  `[phrasebank] generated ${codes.length} language pack(s): ${summary}${
    fixture ? " (fixture)" : release ? " (release)" : ""
  }`,
);
