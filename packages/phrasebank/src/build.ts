import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { loadAll, releaseErrors } from "./loader";

const root = fileURLToPath(new URL("../", import.meta.url));
const release = process.argv.includes("--release");
const data = loadAll();

if (data.warnings.length) {
  console.warn(`[phrasebank] ${data.warnings.length} warning(s) in development data:`);
  for (const warning of data.warnings.slice(0, 20)) console.warn(`  - ${warning}`);
  if (data.warnings.length > 20) console.warn(`  ... and ${data.warnings.length - 20} more`);
}

if (release) {
  const errors = releaseErrors(data);
  if (errors.length) {
    console.error(`[phrasebank] release build failed with ${errors.length} error(s):`);
    for (const error of errors) console.error(`  - ${error}`);
    process.exit(1);
  }
}

const output = `// Generated by src/build.ts — do not edit by hand.
import type { PhraseEntry, TranslationUnit } from "@zteam/shared";

export const tmVersion = ${JSON.stringify(data.tmVersion)};
export const phrasebankVersion = ${JSON.stringify(data.phrasebankVersion)};

export const translationUnits: TranslationUnit[] = ${JSON.stringify(data.translationUnits, null, 2)};

export const phrases: PhraseEntry[] = ${JSON.stringify(data.phrases, null, 2)};

export const numbers = ${JSON.stringify(data.numbers, null, 2)} as const;
`;

writeFileSync(`${root}src/generated.ts`, output, "utf8");
console.log(
  `[phrasebank] generated ${data.translationUnits.length} TM units and ${data.phrases.length} phrases${
    release ? " (release)" : ""
  }`,
);
