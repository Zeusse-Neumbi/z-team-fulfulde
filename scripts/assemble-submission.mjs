#!/usr/bin/env node
/**
 * Assemble the local submission folder and its checksums.
 *
 *   pnpm note:build
 *   pnpm package
 *   pnpm submission
 *
 * The Google Form upload is still manual; this script only makes the local
 * package complete and gives the SHA-256 of the exact files to upload.
 */
import { createHash } from "node:crypto";
import { copyFileSync, existsSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { basename, dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { APP_VERSION, NOTE_VERSION } from "./version.mjs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const outDir = resolve(join(root, "submission"));
const note = join(root, `dist/Z-Team_Fulfulde_Assistant_Technical_Note_v${NOTE_VERSION}.pdf`);
const zip = join(root, `dist/zteam-fulfulde-extension-v${APP_VERSION}.zip`);

mkdirSync(outDir, { recursive: true });

const missing = [note, zip].filter((path) => !existsSync(path));
if (missing.length > 0) {
  console.error("[submission] missing:");
  for (const path of missing) console.error(`  ${path}`);
  console.error("Run `pnpm note:build` and `pnpm package` first.");
  process.exit(1);
}

function sha256(path) {
  const hash = createHash("sha256");
  hash.update(readFileSync(path));
  return hash.digest("hex");
}

const files = [note, zip];
const lines = [];

for (const path of files) {
  const target = join(outDir, basename(path));
  copyFileSync(path, target);
  const size = (statSync(target).size / 1024 / 1024).toFixed(2);
  lines.push(`${sha256(target)}  ${basename(target)}`);
  console.log(`[submission] ${basename(target)}  ${size} MB`);
}

writeFileSync(join(outDir, "SHA256SUMS.txt"), `${lines.join("\n")}\n`);

const readme = `# Submission package

Generated by \`pnpm submission\` on ${new Date().toISOString().slice(0, 10)}.

| File | Purpose |
| --- | --- |
| \`${basename(note)}\` | Documentation (5 pages max, <10 MB) |
| \`${basename(zip)}\` | Extension (unzip, load unpacked) |
| \`SHA256SUMS.txt\` | Checksums |

## Form values

| Field | Value |
| --- | --- |
| Nom du prototype | Z-Team Fulfulde Assistant |
| Nom de l'équipe | Z-Team |
| Ville de l'équipe | Douala |
| Nombre de membres | 3 |
| Nom des membres | fill in the form only; not stored here |
| Responsable | fill in the form only; not stored here |
| E-mail | fill in the form only; not stored here |
| Téléphone/WhatsApp | fill in the form only; not stored here |
| Lien vidéo | fill in the form only; not stored here |
| Documentation | the PDF above |
| Lien du dépôt GitHub | https://github.com/Zeusse-Neumbi/z-team-fulfulde |
| Extension | the ZIP above |

## Before submitting

- [ ] \`sha256sum -c SHA256SUMS.txt\` passes.
- [ ] The PDF is French, 5 pages max, under 10 MB, no \`[[...]]\`.
- [ ] The ZIP is under 10 MB and installs in a clean Chrome profile.
- [ ] The video link works in incognito.
- [ ] The GitHub link works in incognito.
- [ ] The form's Extension field accepts the ZIP (test with **Add file**, then cancel).
- [ ] A backup copy exists outside the repository.
`;

writeFileSync(join(outDir, "README.md"), readme);

console.log(`\n[submission] ${outDir}`);
console.log("[submission] files:");
for (const entry of readdirSync(outDir).sort()) console.log(`  ${entry}`);
console.log("\n[submission] verify:");
console.log(`  cd ${outDir} && sha256sum -c SHA256SUMS.txt`);
console.log("[submission] the form upload is still manual.");
